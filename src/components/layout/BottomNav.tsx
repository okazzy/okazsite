const navItems = [
  { href: '/' as const, labelKey: 'navHome' as const, Icon: HomeIcon },
  { href: '/listen' as const, labelKey: 'navListen' as const, Icon: HeadphonesIcon },
  { href: '/watch' as const, labelKey: 'navWatch' as const, Icon: PlayCircleIcon },
  { href: '/favorites' as const, labelKey: 'navFavourites' as const, Icon: HeartIcon },
  { href: '/settings' as const, labelKey: 'navSettings' as const, Icon: SettingsIcon },
];

export default function BottomNav({ locale }: { locale: string }) {
  const t = useTranslations();
  const pathname = usePathname();

  const isActive = (href: string) => {
    if (href === '/') return pathname === '/';
    return pathname.startsWith(href);
  };

  return (
    <nav className="bottom-nav">
      {navItems.map((item) => (
        <Link
          key={item.href}
          href={item.href}
          className={`bottom-nav-item ${isActive(item.href) ? 'active' : ''}`}
        >
          <item.Icon />
          <span>{t(item.labelKey)}</span>
        </Link>
      ))}
    </nav>
  );
}
